const monthLabels = ["январь", "февраль", "март", "апрель", "май", "июнь", "июль", "август", "сентябрь", "октябрь", "ноябрь", "декабрь"] as const;

type ChartRow = readonly [artist: string, title: string, rank: number];

function slug(value: string) {
  return value
    .normalize("NFKC")
    .toLocaleLowerCase("ru-RU")
    .replace(/ё/g, "е")
    .replace(/[^a-zа-я0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

const MAX_CANDIDATES = 5;

function titleKey(title: string) {
  return slug(title.replace(/[!?.…]+$/u, ""));
}

// Curated top rows first, then further ranked rows of the same poll (rank order) up to five.
function withPollRows(key: string, rows: readonly ChartRow[]): readonly ChartRow[] {
  const merged = [...rows];
  const seen = new Set(rows.map(([, title]) => titleKey(title)));
  const extra = [...(ZD_MK_EXTRA_1987_1991[key] ?? [])].sort((a, b) => a[2] - b[2]);
  for (const row of extra) {
    if (merged.length >= MAX_CANDIDATES) break;
    if (seen.has(titleKey(row[1]))) continue;
    seen.add(titleKey(row[1]));
    merged.push(row);
  }
  return merged;
}

function monthlyChart(year: number, month: number, issueDate: string, curatedRows: readonly ChartRow[]): HistoricalBroadcast {
  const monthValue = String(month).padStart(2, "0");
  const rows = withPollRows(`${year}-${monthValue}`, curatedRows);
  const monthLabel = monthLabels[month - 1];
  const issueLabel = issueDate.split("-").reverse().join(".");
  return {
    chartDate: `${year}-${monthValue}-15`,
    dateLabel: `${monthLabel} ${year} · опубликовано ${issueLabel}` ,
    archiveYear: year,
    programLabel: "«Звуковая дорожка» МК",
    anchorKind: "месячный чарт",
    candidates: rows.map(([artist, title, rank]) => {
      const rowSlug = slug(`${artist}-${title}`);
      return {
        artist,
        title,
        sources: [
          {
            id: `zd-mk-${year}-${monthValue}-${rank}-${rowSlug}` ,
            label: `«Звуковая дорожка» МК: #${rank} за ${monthLabel} ${year} · выпуск ${issueLabel}` ,
            url: chartSourceUrl,
            kind: "читательский чарт",
            rank,
          },
          {
            id: `press-archive-${year}-${monthValue}-${rowSlug}` ,
            label: `Архив хит-парадов СССР за ${year} год` ,
            url: annualArchiveUrls[year],
            kind: "архив прессы",
          },
        ],
      };
    }),
  };
}

