import type { PilotCandidate } from "./pilot-2017";

export type DigitalSalesIssue = {
  year: number;
  weeks: readonly number[];
  periodLabel: string;
  sourceUrl: string;
  candidates: readonly PilotCandidate[];
};

type SalesRow = readonly [artist: string, title: string, rank: number];

function slug(value: string) {
  return value
    .normalize("NFKC")
    .toLocaleLowerCase("ru-RU")
    .replace(/ё/g, "е")
    .replace(/[^a-zа-я0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function issue(year: number, weeks: readonly number[], sourceUrl: string, rows: readonly SalesRow[]): DigitalSalesIssue {
  const periodLabel = `${weeks.length === 1 ? "неделя" : "недели"} ${weeks.join("–")} · ${year}`;
  return {
    year,
    weeks,
    periodLabel,
    sourceUrl,
    candidates: rows.map(([artist, title, rank]) => ({
      artist,
      title,
      score: 260 - rank * 12,
      shazamRank: null,
      signalTypes: 1,
      sources: [
        {
          id: `2m-lenta-${year}-${weeks.join("-")}-${slug(title)}`,
          label: `2М / Lenta.ru: #${rank} в цифровых продажах · ${periodLabel}`,
          url: sourceUrl,
          kind: "цифровые продажи",
          rank,
        },
      ],
    })),
  };
}

