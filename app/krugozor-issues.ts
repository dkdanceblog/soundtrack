const MONTHS_RU = ["январь", "февраль", "март", "апрель", "май", "июнь", "июль", "август", "сентябрь", "октябрь", "ноябрь", "декабрь"];

function issueCandidate(key: string, [artist, title]: KrugozorTrack): HistoricalBroadcastCandidate {
  const [year, month] = key.split("-").map(Number);
  return {
    artist,
    title,
    sources: [{
      id: `krugozor-tunnel-${key}-${canonical(`${artist} ${title}`).replace(/ /g, "-")}`,
      label: `Содержание звуковых страниц «Кругозора» № ${month} за ${year} год: «${title}» — ${artist}. Подтверждает месяц публикации, а не пик популярности.`,
      url: `https://tunnel.ru/post-${key}`,
      kind: "датированное содержание выпуска",
    }],
  };
}

const identity = (entry: { artist: string; title: string }) => `${canonical(entry.artist)}|${canonical(entry.title)}`;

// Month-only anchors built from each issue. Songs already present in the curated
// anchors of that month are skipped, so nothing is duplicated or moved between months.
// These anchors never replace the curated choice for a month: hits.ts uses them only to
// list other songs of the same month (alternatives), and as the main source for months
// that have no curated anchor at all.
export function krugozorAnchors(curated: readonly HistoricalBroadcast[]): HistoricalBroadcast[] {
  const result: HistoricalBroadcast[] = [];
  for (const [key, tracks] of Object.entries(KRUGOZOR_ISSUES)) {
    const [year, month] = key.split("-").map(Number);
    const taken = new Set(curated.filter((anchor) => anchor.chartDate.startsWith(key)).flatMap((anchor) => anchor.candidates.map(identity)));
    const fresh = tracks.map((track) => issueCandidate(key, track)).filter((candidate) => !taken.has(identity(candidate)));
    if (!fresh.length) continue;
    result.push({
      chartDate: `${key}-15`, dateLabel: `${MONTHS_RU[month - 1]} ${year}`, archiveYear: year,
      programLabel: `«Кругозор» № ${month}`, anchorKind: "месячный релиз", candidates: fresh,
    });
  }
  return result;
}
