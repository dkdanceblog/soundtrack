function slug(value: string) {
  return value.normalize("NFKC").toLocaleLowerCase("ru-RU").replace(/ё/g, "е").replace(/[^a-zа-я0-9]+/g, "-").replace(/^-|-$/g, "");
}

const stamp = (ts: string) => Date.UTC(Number(ts.slice(0, 4)), Number(ts.slice(4, 6)) - 1, Number(ts.slice(6, 8)));
const baseTitle = (title: string) => slug(title.replace(/[([].*$/, ""));

function isoWeek(date: string) {
  const active = new Date(`${date}T12:00:00Z`);
  const day = active.getUTCDay() || 7;
  active.setUTCDate(active.getUTCDate() + 4 - day);
  const year = active.getUTCFullYear();
  const start = Date.UTC(year, 0, 1);
  return { year, week: Math.ceil(((active.getTime() - start) / 86400000 + 1) / 7) };
}

export const ITUNES_RU_2014: readonly DigitalSalesIssue[] = SNAPSHOTS.map((snapshot) => {
  const date = `${snapshot.ts.slice(0, 4)}-${snapshot.ts.slice(4, 6)}-${snapshot.ts.slice(6, 8)}`;
  const shown = date.split("-").reverse().join(".");
  const { year, week } = isoWeek(date);
  const sourceUrl = `https://web.archive.org/web/${snapshot.ts}/http://www.apple.com/ru/itunes/charts/songs/`;
  // As for streaming snapshots: the same song must be seen again 7–31 days apart.
  const seenAgain = (title: string) => SNAPSHOTS.some((other) => {
    const gap = Math.abs(stamp(other.ts) - stamp(snapshot.ts)) / 86400000;
    return gap >= 7 && gap <= 31 && other.tracks.some(([, otherTitle]) => baseTitle(otherTitle) === baseTitle(title));
  });
  const eligible = snapshot.tracks.filter(([artist, title]) => isEligibleRussianLanguageTrack(title, artist) && seenAgain(title)).slice(0, 8);
  return {
    year, weeks: [week], periodLabel: `снимок ${shown}`, sourceUrl,
    candidates: eligible.map(([artist, title, rank], index) => ({
      artist, title, score: 260 - (index + 1) * 12, shazamRank: null, signalTypes: 1,
      sources: [{
        id: `itunes-ru-${snapshot.ts.slice(0, 8)}-${slug(title)}`,
        label: `iTunes Россия: #${rank} в общем чарте песен · снимок страницы ${shown} · Wayback Machine`,
        url: sourceUrl, kind: "цифровые продажи", rank,
      }],
    })),
  };
});
