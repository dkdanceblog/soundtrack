const dayStamp = (date: string) => Date.parse(`${date}T12:00:00Z`);
const shownRange = (monday: string) => {
  const end = new Date(dayStamp(monday) + 6 * 86400000).toISOString().slice(0, 10);
  return `${monday.slice(8, 10)}.${monday.slice(5, 7)}–${end.split("-").reverse().join(".")}`;
};

export const ITUNES_RU_LENTA: readonly DigitalSalesIssue[] = LENTA_WEEKS.map((week) => {
  const { year, week: iso } = isoWeek(week.monday);
  const seenAgain = (title: string) => LENTA_WEEKS.some((other) => {
    const gap = Math.abs(dayStamp(other.monday) - dayStamp(week.monday)) / 86400000;
    return gap >= 7 && gap <= 31 && other.tracks.some(([, otherTitle]) => baseTitle(otherTitle) === baseTitle(title));
  });
  const eligible = week.tracks.filter(([artist, title]) => isEligibleRussianLanguageTrack(title, artist) && seenAgain(title));
  const period = shownRange(week.monday);
  return {
    year, weeks: [iso], periodLabel: `неделя ${period}`, sourceUrl: week.url,
    candidates: eligible.map(([artist, title, rank], index) => ({
      artist, title, score: 260 - (index + 1) * 12, shazamRank: null, signalTypes: 1,
      sources: [{
        id: `itunes-ru-lenta-${week.monday}-${slug(title)}`,
        label: `iTunes Россия: #${rank} в недельном чарте песен · продажи ${period} · Lenta.ru`,
        url: week.url, kind: "цифровые продажи", rank,
      }],
    })),
  };
});
