const RUSSIAN_RADIO_2003 = "https://rusradio.ru/news/zolotoi-grammofon-2003";

const slug = (value: string) => value.normalize("NFKD").toLocaleLowerCase("ru-RU")
  .replace(/[^a-zа-я0-9]+/g, "-").replace(/^-|-$/g, "");

function source(id: string, label: string, url: string, kind: string): PilotSource {
  return { id, label, url, kind };
}

function candidates(year: number, chartDate: string, tracks: readonly Track[], sourcesFor: (track: Track) => readonly PilotSource[]) {
  return tracks.map(([artist, title]) => ({ artist, title, chartDate, sources: sourcesFor([artist, title]) }));
}

const festival = (year: 1983 | 1984, date: string, archive: string) => (track: Track) => {
  const id = slug(`${track[0]}-${track[1]}`);
  return [
    source(`song-${year}-${id}`, `«Песня-${String(year).slice(2)}»: финальный телеэфир ${date}`, year === 1983 ? SONG_83 : SONG_84, "телевизионный выпуск"),
    source(`music-press-${year}-${id}`, `Архив музыкальной прессы: песня в списке ${year} года`, archive, "годовой слушательский архив"),
  ];
};

const annualArchive = (year: number, url = MUSIC_PRESS_1992_2000) => (track: Track) => [
  source(`annual-${year}-${slug(`${track[0]}-${track[1]}`)}`, `Годовой архив популярных песен: ${year}`, url, "годовой слушательский архив"),
];

const award = (year: number, date: string, secondary?: { url: string; label: string; kind: string }) => (track: Track) => {
  const id = slug(`${track[0]}-${track[1]}`);
  return [
    source(`golden-gramophone-${year}-${id}`, `«Золотой граммофон — ${year}»: лауреат, церемония ${date}`, GOLDEN_GRAMOPHONE, "слушательская музыкальная премия"),
    ...(secondary ? [source(`annual-check-${year}-${id}`, secondary.label, secondary.url, secondary.kind)] : []),
  ];
};

