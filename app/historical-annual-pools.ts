const SONG_94 = "https://www.vremya.tv/announce/12044";
const GOLDEN_GRAMOPHONE = "https://ru.wikipedia.org/wiki/Список_лауреатов_премии_«Золотой_граммофон»";
const RUSSIAN_RADIO_2001 = "https://rusradio.ru/news/zolotoi-grammofon-2001";
