"""Build app/zd-mk-extra-1987-1991.ts from data-src/zd-mk-1987-1991.txt.

Each line: "МЕСЯЦА DD.MM.YY|rank~«title» — artist (weeks)|...". The heading month is
the chart month; the date is the issue date (December charts are published next year).
"""
import json, re, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
MONTHS = {"ЯНВАР":1,"ФЕВРАЛ":2,"МАРТ":3,"АПРЕЛ":4,"МА":5,"ИЮН":6,"ИЮЛ":7,"АВГУСТ":8,"СЕНТЯБР":9,"ОКТЯБР":10,"НОЯБР":11,"ДЕКАБР":12}
def month_of(word):
    for k in sorted(MONTHS, key=len, reverse=True):
        if word.startswith(k): return MONTHS[k]
    raise ValueError(word)
out = {}
for line in (ROOT/"data-src/zd-mk-1987-1991.txt").read_text().splitlines():
    if not line.strip(): continue
    head, *cells = line.split("|")
    word, date = head.split()
    d, m, y = date.split(".")
    month, year = month_of(word), 1900 + int(y)
    if month > int(m): year -= 1
    rows = []
    for cell in cells:
        rank, text = cell.split("~", 1)
        text = re.sub(r"\s*\(\d+\)\s*$", "", text)
        text = re.sub(r"»\s+\(«[^»]+»\)", "»", text)
        mt = re.match(r"«(.+?)»\s+—\s+(.+)$", text)
        if not mt: raise ValueError(cell)
        title, artist = mt.group(1), mt.group(2).strip()
        rows.append([artist, title, int(rank)])
    out[f"{year}-{month:02d}"] = rows
body = ",\n".join(f"  {json.dumps(k)}: [\n" + ",\n".join(f"    [{json.dumps(a, ensure_ascii=False)}, {json.dumps(t, ensure_ascii=False)}, {r}]" for a,t,r in v) + ",\n  ]" for k,v in out.items())
(ROOT/"app/zd-mk-extra-1987-1991.ts").write_text(
 "// Generated by scripts/build-zd-mk-extra.py from data-src/zd-mk-1987-1991.txt. Do not edit.\n"
 "// Full ranked cells of the monthly «Звуковая дорожка» MK reader polls (Сычёв, «Хит-парады в СССР»).\n"
 "export const ZD_MK_EXTRA_1987_1991: Readonly<Record<string, readonly (readonly [artist: string, title: string, rank: number])[]>> = {\n"
 + body + ",\n};\n")
print(len(out), "months")
