"""Build app/gramophone-alternatives-data.ts from data-src/gramophone-alternatives.txt.

Top-8 rows of the «Золотой граммофон» issues nearest to dates (1999–2025) whose main
evidence had fewer than three candidates. Read from chartoteka.com on 2026-10-26 and
verified by SHA-256 of the whole export. Format: date|rank~artist~title~weeks|...
Only rows with at least two weeks in the chart are kept.
"""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
issues = []
for line in (root / "data-src/gramophone-alternatives.txt").read_text(encoding="utf-8").strip().splitlines():
    date, *cells = line.split("|")
    tracks = []
    for cell in cells:
        rank, artist, title, weeks = cell.split("~")
        if int(weeks) >= 2:
            tracks.append({"rank": int(rank), "artist": artist, "title": title})
    issues.append({"date": date, "tracks": tracks})
(root / "app/gramophone-alternatives-data.ts").write_text(
    "// Generated by scripts/build-gramophone-alternatives.py. Do not edit by hand.\n"
    "export const GRAMOPHONE_ALT_ISSUES: readonly { date: string; tracks: readonly { rank: number; artist: string; title: string }[] }[] = "
    + json.dumps(issues, ensure_ascii=False) + ";\n", encoding="utf-8")
print(len(issues), "issues")
