#!/usr/bin/env python3
"""Builds app/radio-weekly-1995-2003-data.ts from data-src/*.txt.

Source rows were read from the chartoteka.com archive API (issue pages
https://chartoteka.com/charts/<chart>/<date>) on 2026-10-03 and verified line by
line against the live archive with SHA-256 hashes of the normalised rows.
Format: date|rank~artist~title[~weeks]|...
"""
import json, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
def load(name, chart, with_weeks):
    issues = []
    for line in (root / "data-src" / name).read_text(encoding="utf-8").strip().splitlines():
        date, *cells = line.split("|")
        tracks = []
        for cell in cells:
            parts = cell.split("~")
            if with_weeks:
                rank, artist, title, weeks = parts
                if int(weeks) < 2:
                    continue  # same threshold as the 2004 module: at least two weeks in the chart
            else:
                rank, artist, title = parts  # already filtered to >= 2 weeks when exported
            tracks.append({"rank": int(rank), "artist": artist, "title": title})
        issues.append({"chart": chart, "date": date, "tracks": tracks})
    return issues

issues = (load("maximum-1995-1999.txt", "maximum", False)
          + load("gramophone-1999-2000.txt", "gramophone", True)
          + load("gramophone-2001-2003.txt", "gramophone", False)
          # Latest issues (read 2026-10-26, verified by SHA-256 of the whole export).
          + load("gramophone-2026.txt", "gramophone", True)
          # «Чартова дюжина» (listener vote), read 2026-11-12: only fills recent days with no
          # «Золотой граммофон» issue nearby (see radio-weekly-1995-2003.ts).
          + load("chartova-2026.txt", "chartova", True))
issues.sort(key=lambda issue: (issue["date"], issue["chart"]))
out = root / "app" / "radio-weekly-1995-2003-data.ts"
out.write_text(
    "// Generated by scripts/build-radio-weekly.py from data-src/*.txt. Do not edit by hand.\n"
    "export type RadioIssue = { chart: \"maximum\" | \"gramophone\" | \"chartova\"; date: string; tracks: readonly { rank: number; artist: string; title: string }[] };\n"
    f"export const RADIO_ISSUES_1995_2003: readonly RadioIssue[] = {json.dumps(issues, ensure_ascii=False)};\n",
    encoding="utf-8")
print(len(issues), "issues")
