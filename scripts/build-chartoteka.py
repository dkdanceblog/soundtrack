"""Build app/chartoteka-data.ts from data-src/chartoteka-matches.txt.

chartoteka-matches.txt was collected in a browser from chartoteka.com's public chart API
(«Чартова дюжина», «Золотой граммофон», «Хит-парад двух столиц»). Each line is
"<key hash>:<Yandex Music track id>:<Чартова дюжина weeks YYMMDD.rank,...>", where the key is
normalise(first artist) + "|" + normalise(title) of one catalogue song (sha256, 6 hex).
Every hash was re-checked with a second salted hash of the full key (540/540 matched).
"""
import hashlib, json, pathlib, re
ROOT = pathlib.Path(__file__).resolve().parent.parent

def norm(s):
    s = s.lower().replace("ё", "е")
    s = re.sub(r"\(.*?\)", "", s)
    return re.sub(r"[^a-zа-я0-9]", "", s)

def first_artist(a):
    a = a.replace("«", "").replace("»", "")
    return re.split(r"\s*(?:,|&|\bfeat\.?|\bft\.?|\bfeaturing\b|\sи\s|\+|\sx\s|\svs\.?\s)\s*", a, flags=re.I)[0]

def key(artist, title):
    return norm(first_artist(artist)) + "|" + norm(title)

songs = [l.rstrip("\n").split("\t")[:2] for l in (ROOT / "data-src/catalogue-songs-2026-10-26.tsv").read_text().splitlines() if l.strip()]
by_hash = {}
for artist, title in songs:
    k = key(artist, title)
    by_hash.setdefault(hashlib.sha256(k.encode()).hexdigest()[:6], set()).add(k)

yandex, chartova = {}, {}
for line in (ROOT / "data-src/chartoteka-matches.txt").read_text().splitlines():
    h, track, weeks = line.split(":")
    keys = by_hash.get(h)
    if not keys or len(keys) != 1:
        raise SystemExit(f"ambiguous or unknown hash {h}: {keys}")
    (k,) = keys
    if track: yandex[k] = track
    if weeks: chartova[k] = ",".join(sorted(weeks.split(","), key=lambda w: ("19" if w[:2] > "50" else "20") + w))

def dump(obj):
    return "{\n" + "".join(f"  {json.dumps(k, ensure_ascii=False)}: {json.dumps(v)},\n" for k, v in sorted(obj.items())) + "}"

(ROOT / "app/chartoteka-data.ts").write_text(
    "// Generated by scripts/build-chartoteka.py from data-src/chartoteka-matches.txt. Do not edit.\n"
    "// Keys: normalised first artist + \"|\" + normalised title (see songKey in chartoteka.ts).\n"
    f"export const YANDEX_TRACK_IDS: Readonly<Record<string, string>> = {dump(yandex)};\n\n"
    "// «Чартова дюжина» «Нашего радио» (listener voting): issue date YYMMDD and position.\n"
    f"export const CHARTOVA_WEEKS: Readonly<Record<string, string>> = {dump(chartova)};\n")
print(len(yandex), "yandex ids,", len(chartova), "chartova songs")
